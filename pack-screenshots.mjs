// Packs screenshots-src/*.jpg into screenshots-data.ts, one single-line
// base64 payload per screenshot, so main.ts can materialize them into the
// output's screenshots/ folder without any binary file in git history.
// Run: node pack-screenshots.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = fileURLToPath(new URL('.', import.meta.url));
const srcDir = join(here, 'screenshots-src');
const names = readdirSync(srcDir).filter((n) => /\.(jpe?g|png)$/i.test(n)).sort();
if (names.length < 3 || names.length > 4) throw new Error(`need 3-4 screenshots, found ${names.length}`);

const lines = [
  '// Generated by pack-screenshots.mjs — base64 payloads, one line each.',
  'export interface PackedShot { name: string; base64: string }',
  'export const SCREENSHOTS: PackedShot[] = [',
];
for (const name of names) {
  const b64 = readFileSync(join(srcDir, name)).toString('base64');
  lines.push(`  { name: ${JSON.stringify(name)}, base64: '${b64}' },`);
}
lines.push('];', '');
writeFileSync(join(here, 'screenshots-data.ts'), lines.join('\n'));
console.log(`packed ${names.length} screenshots: ${names.join(', ')}`);
